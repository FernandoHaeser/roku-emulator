#!/usr/bin/env node
// Derives system font metrics from device calibration probes and writes the
// tables used by the engine (Rust) and the Canvas2D host (TypeScript):
//   fidelity/scenegraph/font-advances  -> per-character advance and end offset
//   fidelity/scenegraph/font-kerning   -> kerning pairs (55 px, scaled by size)
//   fidelity/scenegraph/label-metrics  -> line heights
// Only measurements are stored (no glyph data). Run: node scripts/gen-font-metrics.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const golden = (probe) =>
  readFileSync(join(root, "fidelity/scenegraph", probe, "golden/console.txt"), "utf8");

/** Order matters: index = font id in the display list. */
const FONTS = [
  ["SmallestSystemFont", 27],
  ["SmallestBoldSystemFont", 27],
  ["SmallSystemFont", 33],
  ["SmallBoldSystemFont", 33],
  ["MediumSystemFont", 36],
  ["MediumBoldSystemFont", 36],
  ["LargeSystemFont", 45],
  ["LargeBoldSystemFont", 45],
  ["ExtraLargeSystemFont", 55],
  ["ExtraLargeBoldSystemFont", 55],
];
const KERN_SIZE = 55;
/** Kerning below this magnitude is indistinguishable from rounding noise. */
const KERN_NOISE = 1.5;

// --- advances: "font|code|w10|w30" ------------------------------------------
const advance20 = new Map(); // font -> Map(code -> advance * 20)
const offset = new Map(); // font -> Map(code -> w10 - 10 * advance)
const codes = [];
for (const line of golden("font-advances").split("\n")) {
  const match = /^(\w+)\|\s*(\d+)\|\s*([\d.]+)\s*\|\s*([\d.]+)/.exec(line);
  if (!match) continue;
  const [, font, code, w10, w30] = match;
  const a20 = Math.round(Number(w30) - Number(w10)); // (w30 - w10) / 20 * 20
  if (!advance20.has(font)) {
    advance20.set(font, new Map());
    offset.set(font, new Map());
  }
  advance20.get(font).set(Number(code), a20);
  offset.get(font).set(Number(code), Math.round(Number(w10) - a20 / 2));
  if (font === FONTS[0][0]) codes.push(Number(code));
}

// --- kerning: "font|a|b|width" ----------------------------------------------
const kerning = { regular: new Map(), bold: new Map() };
for (const line of golden("font-kerning").split("\n")) {
  const match = /^(\w+)\|\s*(\d+)\|\s*(\d+)\|\s*([\d.]+)/.exec(line);
  if (!match) continue;
  const [, font, a, b, width] = match;
  const adv = advance20.get(font);
  const kern =
    Number(width) - (adv.get(Number(a)) + adv.get(Number(b))) / 2 - offset.get(font).get(Number(b));
  if (kern > -KERN_NOISE) continue;
  const half = Math.round(kern * 2);
  kerning[font.includes("Bold") ? "bold" : "regular"].set(Number(a) * 65536 + Number(b), half);
}

// --- line heights: "Font | text | w x h" ------------------------------------
const lineHeight = new Map();
for (const line of golden("label-metrics").split("\n")) {
  const match = /^(\w+SystemFont) \| .* \|\s+\d+\s+x\s+(\d+)/.exec(line);
  if (match) lineHeight.set(match[1], Number(match[2]));
}

const missing = FONTS.filter(([name]) => !advance20.has(name) || !lineHeight.has(name));
if (missing.length) throw new Error(`missing calibration for ${missing.map(([n]) => n)}`);

const chars = String.fromCodePoint(...codes);
const rows = (map) => FONTS.map(([name]) => codes.map((code) => map.get(name).get(code)));
const pairs = (map) => [...map.entries()].sort((x, y) => x[0] - y[0]);
const header = (comment) =>
  `${comment} Generated by scripts/gen-font-metrics.mjs from device calibration probes.\n${comment} Do not edit by hand; re-record the probes and regenerate.\n`;

// --- Rust ---------------------------------------------------------------------
const rustRows = (values) => values.map((row) => `    [${row.join(", ")}],`).join("\n");
const rust = `${header("//!")}
/// Characters covered by the tables (index = column).
pub const CHARS: &str = ${JSON.stringify(chars)};
pub const CHAR_COUNT: usize = ${codes.length};
/// System fonts: (name, FHD size, FHD line height). Index = font id.
pub const FONTS: [(&str, u32, u32); ${FONTS.length}] = [
${FONTS.map(([name, size]) => `    (${JSON.stringify(name)}, ${size}, ${lineHeight.get(name)}),`).join("\n")}
];
/// Advance per character in 1/20 px (FHD).
pub const ADVANCE_20: [[u16; CHAR_COUNT]; ${FONTS.length}] = [
${rustRows(rows(advance20))}
];
/// Width correction contributed by the last character (bearing), in px.
pub const END_OFFSET: [[i8; CHAR_COUNT]; ${FONTS.length}] = [
${rustRows(rows(offset))}
];
/// Kerning at ${KERN_SIZE} px in 1/2 px: (first << 16 | second, kern). Sorted by key.
pub const KERN_SIZE: f64 = ${KERN_SIZE}.0;
pub const KERN_REGULAR: [(u32, i8); ${kerning.regular.size}] = [
${pairs(kerning.regular)
  .map(([k, v]) => `    (${k}, ${v}),`)
  .join("\n")}
];
pub const KERN_BOLD: [(u32, i8); ${kerning.bold.size}] = [
${pairs(kerning.bold)
  .map(([k, v]) => `    (${k}, ${v}),`)
  .join("\n")}
];
`;
writeFileSync(join(root, "crates/brs-core/src/sg/font_metrics.rs"), rust);

// --- TypeScript ---------------------------------------------------------------
const ts = `${header("//")}
export const CHARS = ${JSON.stringify(chars)};
/** [name, FHD size, FHD line height]; index = font id. */
export const FONTS: readonly (readonly [string, number, number])[] = ${JSON.stringify(
  FONTS.map(([name, size]) => [name, size, lineHeight.get(name)]),
)};
/** Advance per character in 1/20 px (FHD), rows by font id. */
export const ADVANCE_20: readonly (readonly number[])[] = ${JSON.stringify(rows(advance20))};
export const END_OFFSET: readonly (readonly number[])[] = ${JSON.stringify(rows(offset))};
export const KERN_SIZE = ${KERN_SIZE};
/** first << 16 | second -> kern in 1/2 px at KERN_SIZE. */
export const KERN_REGULAR: readonly (readonly [number, number])[] = ${JSON.stringify(pairs(kerning.regular))};
export const KERN_BOLD: readonly (readonly [number, number])[] = ${JSON.stringify(pairs(kerning.bold))};
`;
writeFileSync(join(root, "apps/web/src/worker/fontMetrics.generated.ts"), ts);
console.log(
  `font metrics: ${codes.length} chars x ${FONTS.length} fonts, kerning ${kerning.regular.size}/${kerning.bold.size} pairs`,
);
